#!/usr/bin/env python3
"""Generates daemon/src/ad9361/baseband_fir.rs, the AD9363 programmable FIRs
used for sample rates below the halfband-only minimum.

Each filter is a 127-tap equiripple low-pass, padded with one zero to the 128
taps the AD9361 FIR accepts, so its group delay is a whole 63 samples at the
filter's high-rate side. The passband runs to 0.42 and the stopband starts at
0.58 of the low sample rate, so the same coefficients serve any rate in
the range. Coefficients are Q15 scaled to a DC gain equal to the ratio. The
TX interpolator divides by the ratio, so it runs at unity gain with its gain
stage at 0 dB. The RX decimator does not, so the daemon sets its gain stage to
-6 dB at x2 and -12 dB at x4.

Run with scipy installed:

    python3 tools/design_baseband_fir.py > daemon/src/ad9361/baseband_fir.rs
"""

import numpy as np
from scipy import signal

TAPS = 127
PADDED_TAPS = 128
PASSBAND_EDGE = 0.42
STOPBAND_EDGE = 0.58
STOPBAND_WEIGHT = 10
Q15_ONE = 32768
COEF_MAX = 32767
FACTORS = (2, 4)
RUST_LINE_WIDTH = 100


def design(factor):
    bands = [0, PASSBAND_EDGE / factor, STOPBAND_EDGE / factor, 0.5]
    taps = signal.remez(TAPS, bands, [1, 0], weight=[1, STOPBAND_WEIGHT], fs=1.0)
    taps *= Q15_ONE * factor / taps.sum()
    peak = np.abs(taps).max()
    if peak > COEF_MAX:
        taps *= COEF_MAX / peak
    coefs = np.append(np.round(taps).astype(int), 0)
    assert len(coefs) == PADDED_TAPS
    return coefs


def response(coefs, factor):
    w, h = signal.freqz(coefs / coefs.sum(), worN=16384)
    host = w / np.pi / 2 * factor
    db = 20 * np.log10(np.abs(h) + 1e-12)
    passband = db[host <= PASSBAND_EDGE]
    return passband.max() - passband.min(), db[host >= STOPBAND_EDGE].max()


def rust_array(name, coefs):
    lines = [f"pub const {name}: [i16; {len(coefs)}] = ["]
    row = []
    for value in coefs:
        row.append(f"{value},")
        if len(" ".join(row)) > RUST_LINE_WIDTH - len("    "):
            lines.append("    " + " ".join(row[:-1]))
            row = row[-1:]
    lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def main():
    print("//! AD9363 programmable FIRs for sample rates below the halfband-only minimum.")
    print("//!")
    print("//! Generated by `tools/design_baseband_fir.py`. Do not edit by hand.")
    for factor in FACTORS:
        coefs = design(factor)
        ripple, stop = response(coefs, factor)
        print()
        print(
            f"/// x{factor}: passband ripple {ripple:.3f} dB to {PASSBAND_EDGE} of the sample rate, "
            f"stopband {stop:.1f} dB from {STOPBAND_EDGE}."
        )
        print(rust_array(f"FIR_X{factor}", coefs))


if __name__ == "__main__":
    main()
