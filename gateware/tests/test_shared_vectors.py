"""Cross-check against the vectors the host tools publish.

``tools/vectors/wire_formats.json`` is generated by the host side from its own
implementation. Checking the gateware's packer against it, rather than only
against this repository's own reference, is what catches the two ends drifting
apart: a bug that lives in both `tests/golden.py` and `cores/sample_packer.py`
would pass every other test in here.

Only the codec vectors are checked here. The samples-per-packet entries are
checked by `tools/tests/test_vectors.py`.
"""

import json
from pathlib import Path

import pytest

from tests import golden
from tests.test_sample_packer import pack_through_rtl, unpack_through_rtl

VECTORS = Path(__file__).resolve().parents[2] / "tools" / "vectors" / "wire_formats.json"
FORMATS = {"cs12": golden.FORMAT_CS12, "cs8": golden.FORMAT_CS8,
           "bfp8": golden.FORMAT_BFP8}

pytestmark = pytest.mark.skipif(not VECTORS.exists(),
                                reason="tools/vectors/wire_formats.json is not in this tree")


def load():
    return json.loads(VECTORS.read_text())


def codec_cases():
    if not VECTORS.exists():
        return []
    return [(case["name"], case) for case in load()["codec"]]


@pytest.mark.parametrize("name,case", codec_cases(), ids=lambda v: v if isinstance(v, str) else "")
def test_the_reference_packs_what_the_host_packs(name, case):
    fmt = FORMATS[case["format"]]
    samples = [tuple(pair) for pair in case["samples"]]
    assert golden.pack(fmt, samples).hex() == case["payload_hex"], \
        f"{name}: this repository's reference disagrees with the host's"


@pytest.mark.parametrize("name,case", codec_cases(), ids=lambda v: v if isinstance(v, str) else "")
def test_the_gateware_packs_what_the_host_packs(name, case):
    fmt = FORMATS[case["format"]]
    samples = [tuple(pair) for pair in case["samples"]]
    assert pack_through_rtl(fmt, samples).hex() == case["payload_hex"], \
        f"{name}: the packer disagrees with the host's"


@pytest.mark.parametrize("name,case", codec_cases(), ids=lambda v: v if isinstance(v, str) else "")
def test_the_gateware_unpacks_what_the_host_decodes(name, case):
    fmt = FORMATS[case["format"]]
    payload = bytes.fromhex(case["payload_hex"])
    count = len(case["samples"])
    expected = [tuple(pair) for pair in case["decoded"]]
    assert unpack_through_rtl(fmt, payload, count) == expected, \
        f"{name}: the unpacker disagrees with the host's"


def test_the_bfp8_exponents_agree():
    blocks = load().get("bfp8_blocks", [])
    if not blocks:
        pytest.skip("no bfp8 block vectors published")
    for block in blocks:
        samples = [tuple(pair) for pair in block["samples"]]
        assert golden.bfp_exponent(samples) == block["exponent"], \
            f"exponent for {block.get('name', samples[:2])}"
